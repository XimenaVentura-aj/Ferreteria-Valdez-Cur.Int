let pagina = 1;
const productosPorPagina = 9;

const CART_STORAGE_KEY = "ferrehogar_carrito";

function rutaActualEsPaginaInterna() {
    return window.location.pathname.includes("/pages/");
}

function normalizarRutaImagen(ruta) {
    if (!ruta) return "";
    if (ruta.startsWith("http") || ruta.startsWith("data:")) return ruta;

    const enPaginaInterna = rutaActualEsPaginaInterna();
    if (enPaginaInterna && ruta.startsWith("img/")) return "../" + ruta;
    if (!enPaginaInterna && ruta.startsWith("../")) return ruta.replace(/^\.\.\//, "");
    return ruta;
}

function leerCarrito() {
    try {
        return JSON.parse(localStorage.getItem(CART_STORAGE_KEY)) || [];
    } catch (error) {
        return [];
    }
}

function guardarCarrito(carrito) {
    localStorage.setItem(CART_STORAGE_KEY, JSON.stringify(carrito));
    actualizarContadorCarrito();
}

function extraerProductoDesdeBoton(boton, nombre, cantidad) {
    const tarjeta = boton?.closest(".producto, .producto-card, .card");
    const textoPrecio = tarjeta?.querySelector(".precio")?.textContent || Array.from(tarjeta?.querySelectorAll("p") || [])
        .map(p => p.textContent)
        .find(t => t.toLowerCase().includes("precio")) || "";
    const precio = parseFloat((textoPrecio.match(/[0-9]+(?:[.,][0-9]+)?/) || ["0"])[0].replace(",", "."));
    const imagen = tarjeta?.querySelector("img")?.getAttribute("src") || "";

    return {
        id: nombre.toLowerCase().replace(/[^a-z0-9áéíóúñ]+/gi, "-"),
        nombre,
        precio: isNaN(precio) ? 0 : precio,
        imagen: normalizarRutaImagen(imagen),
        cantidad
    };
}

function agregarCarrito(producto, cantidad = 1) {
    const cantidadFinal = Math.max(1, parseInt(cantidad || 1, 10));
    const boton = typeof event !== "undefined" ? event.currentTarget : null;
    const item = typeof producto === "object"
        ? {
            id: producto.id || producto.nombre.toLowerCase().replace(/[^a-z0-9áéíóúñ]+/gi, "-"),
            nombre: producto.nombre,
            precio: Number(producto.precio) || 0,
            imagen: normalizarRutaImagen(producto.imagen),
            cantidad: cantidadFinal
        }
        : extraerProductoDesdeBoton(boton, producto, cantidadFinal);

    const carrito = leerCarrito();
    const existente = carrito.find(p => String(p.id) === String(item.id) || p.nombre === item.nombre);

    if (existente) {
        existente.cantidad += cantidadFinal;
    } else {
        carrito.push(item);
    }

    guardarCarrito(carrito);
    mostrarToastCarrito(`${item.nombre} agregado al carrito`);
}

function mostrarToastCarrito(mensaje) {
    let toast = document.getElementById("toastCarrito");
    if (!toast) {
        toast = document.createElement("div");
        toast.id = "toastCarrito";
        toast.className = "toast-carrito";
        document.body.appendChild(toast);
    }
    toast.textContent = mensaje;
    toast.classList.add("activo");
    setTimeout(() => toast.classList.remove("activo"), 1800);
}

function obtenerCantidad(id) {
    const input = document.getElementById("cantidad-" + id);
    const valor = parseInt(input?.value || "1", 10);
    return valor > 0 ? valor : 1;
}

function cambiarCantidad(id, cambio) {
    const input = document.getElementById("cantidad-" + id);
    if (!input) return;
    const actual = parseInt(input.value || "1", 10);
    input.value = Math.max(1, actual + cambio);
}

function cambiarCantidadCarrito(id, cambio) {
    const carrito = leerCarrito();
    const item = carrito.find(p => String(p.id) === String(id));
    if (!item) return;
    item.cantidad = Math.max(1, Number(item.cantidad || 1) + cambio);
    guardarCarrito(carrito);
    pintarCarrito();
}

function eliminarProductoCarrito(id) {
    guardarCarrito(leerCarrito().filter(p => String(p.id) !== String(id)));
    pintarCarrito();
}

function actualizarContadorCarrito() {
    const totalItems = leerCarrito().reduce((acc, p) => acc + Number(p.cantidad || 0), 0);
    document.querySelectorAll(".contador-carrito").forEach(el => el.textContent = totalItems);
}

function pintarCarrito() {
    const contenedor = document.getElementById("listaCarrito");
    const totalElemento = document.getElementById("totalCarrito");
    const cantidadResumen = document.getElementById("cantidadResumen");
    if (!contenedor || !totalElemento) return;

    const carrito = leerCarrito();
    const totalItems = carrito.reduce((acc, p) => acc + Number(p.cantidad || 0), 0);
    if (cantidadResumen) cantidadResumen.textContent = totalItems === 1 ? "1 producto" : `${totalItems} productos`;

    if (carrito.length === 0) {
        contenedor.innerHTML = `
            <div class="carrito-vacio carrito-vacio-premium">
                <div class="carrito-vacio-icono"></div>
                <h3>Tu carrito está vacío</h3>
                <p>Agrega productos desde Inicio o Productos para continuar con tu compra.</p>
                <a href="productos.html">Ver productos</a>
            </div>`;
        totalElemento.textContent = "S/. 0.00";
        document.getElementById("btnContinuarDatos").disabled = true;
        actualizarProgresoCheckout(1);
        return;
    }

    document.getElementById("btnContinuarDatos").disabled = false;
    let total = 0;
    contenedor.innerHTML = carrito.map(item => {
        const precio = Number(item.precio || 0);
        const cantidad = Number(item.cantidad || 1);
        const subtotal = precio * cantidad;
        total += subtotal;
        return `
            <article class="carrito-item">
                <div class="carrito-img-wrap">
                    <img src="${normalizarRutaImagen(item.imagen)}" alt="${item.nombre}">
                </div>
                <div class="carrito-info">
                    <span class="item-etiqueta">Producto agregado</span>
                    <h3>${item.nombre}</h3>
                    <div class="item-precios">
                        <p>Precio unitario <strong>S/. ${precio.toFixed(2)}</strong></p>
                        <p>Subtotal <strong>S/. ${subtotal.toFixed(2)}</strong></p>
                    </div>
                </div>
                <div class="carrito-controles" aria-label="Control de cantidad">
                    <button type="button" onclick="cambiarCantidadCarrito('${item.id}', -1)">−</button>
                    <span>${cantidad}</span>
                    <button type="button" onclick="cambiarCantidadCarrito('${item.id}', 1)">+</button>
                </div>
                <button class="btn-eliminar" type="button" title="Eliminar producto" onclick="eliminarProductoCarrito('${item.id}')">🗑</button>
            </article>`;
    }).join("");

    totalElemento.textContent = `S/. ${total.toFixed(2)}`;
}

function actualizarProgresoCheckout(numero) {
    document.querySelectorAll(".progreso-item").forEach((item, index) => {
        item.classList.toggle("activo", index < numero);
    });
}

function mostrarPasoCheckout(paso) {
    const pasos = { pasoDatosCliente: 2, pasoEntrega: 3, pasoPago: 4, mensajeCompraExitosa: 4 };
    actualizarProgresoCheckout(pasos[paso] || 1);
    document.querySelectorAll(".checkout-paso").forEach(sec => sec.classList.remove("activo"));
    document.getElementById(paso)?.classList.add("activo");
    document.getElementById(paso)?.scrollIntoView({ behavior: "smooth", block: "start" });
}

function configurarCheckout() {
    if (!document.getElementById("carritoPage")) return;
    pintarCarrito();

    document.getElementById("btnContinuarDatos")?.addEventListener("click", () => mostrarPasoCheckout("pasoDatosCliente"));

    document.getElementById("formDatosCliente")?.addEventListener("submit", e => {
        e.preventDefault();
        mostrarPasoCheckout("pasoEntrega");
    });

    document.querySelectorAll("[data-entrega]").forEach(btn => {
        btn.addEventListener("click", () => {
            const tipo = btn.dataset.entrega;
            document.querySelectorAll(".opcion-entrega-detalle").forEach(div => div.classList.remove("activo"));
            document.getElementById(tipo === "tienda" ? "detalleTienda" : "detalleDomicilio").classList.add("activo");
        });
    });

    document.getElementById("formDomicilio")?.addEventListener("submit", e => {
        e.preventDefault();
        mostrarPasoCheckout("pasoPago");
    });

    document.getElementById("btnPagoTienda")?.addEventListener("click", () => mostrarPasoCheckout("pasoPago"));

    document.querySelectorAll("[data-pago]").forEach(btn => {
        btn.addEventListener("click", () => {
            document.querySelectorAll("[data-pago]").forEach(b => b.classList.remove("seleccionado"));
            btn.classList.add("seleccionado");
            const metodo = btn.dataset.pago.toUpperCase();
            document.getElementById("pagoSeleccionado").textContent = metodo;
            const qrImagen = document.getElementById("qrPagoImagen");
            if (qrImagen) {
                qrImagen.src = btn.dataset.pago === "plin" ? "../img/plin.jpeg" : "../img/yape.jpeg";
                qrImagen.alt = `QR de pago ${metodo}`;
            }
        });
    });

    document.getElementById("btnConfirmarCompra")?.addEventListener("click", () => {
        localStorage.removeItem(CART_STORAGE_KEY);
        actualizarContadorCarrito();
        pintarCarrito();
        document.querySelectorAll(".checkout-paso").forEach(sec => sec.classList.remove("activo"));
        document.getElementById("mensajeCompraExitosa").classList.add("activo");
        document.getElementById("mensajeCompraExitosa").scrollIntoView({ behavior: "smooth", block: "center" });
    });
}

document.addEventListener("DOMContentLoaded", () => {
    actualizarContadorCarrito();
    configurarCheckout();
});


function agregarCarritoPorId(id) {
    const producto = productosFerreteria.find(p => Number(p.id) === Number(id));
    if (!producto) return;
    agregarCarrito(producto, obtenerCantidad(id));
}

function productosFiltrados() {
    const nombre = (document.getElementById("filtroNombre")?.value || "").toLowerCase().trim();
    const categoria = document.getElementById("filtroCategoria")?.value || "";
    const precioMin = parseFloat(document.getElementById("precioMin")?.value || "");
    const precioMax = parseFloat(document.getElementById("precioMax")?.value || "");
    const orden = document.getElementById("ordenPrecio")?.value || "";

    let lista = productosFerreteria.filter(p => {
        const coincideNombre = p.nombre.toLowerCase().includes(nombre);
        const coincideCategoria = categoria === "" || p.categoria === categoria;
        const coincideMin = isNaN(precioMin) || p.precio >= precioMin;
        const coincideMax = isNaN(precioMax) || p.precio <= precioMax;
        return coincideNombre && coincideCategoria && coincideMin && coincideMax;
    });

    if (orden === "asc") lista.sort((a, b) => a.precio - b.precio);
    if (orden === "desc") lista.sort((a, b) => b.precio - a.precio);

    return lista;
}

function pintarProductos() {
    const grid = document.getElementById("productosGrid");
    if (!grid) return;

    const lista = productosFiltrados();
    const totalPaginas = Math.max(1, Math.ceil(lista.length / productosPorPagina));
    if (pagina > totalPaginas) pagina = totalPaginas;

    const inicio = (pagina - 1) * productosPorPagina;
    const productosPagina = lista.slice(inicio, inicio + productosPorPagina);

    document.getElementById("contadorProductos").textContent = lista.length + " productos encontrados";
    document.getElementById("paginaActual").textContent = "Página " + pagina + " de " + totalPaginas;
    document.getElementById("btnAnterior").disabled = pagina === 1;
    document.getElementById("btnSiguiente").disabled = pagina === totalPaginas;

    if (productosPagina.length === 0) {
        grid.innerHTML = '<div class="sin-productos">No se encontraron productos con esos filtros.</div>';
        return;
    }

    grid.innerHTML = productosPagina.map(p => `
        <article class="card producto-card">
            <img src="${p.imagen}" alt="${p.nombre}">
            <span class="categoria-etiqueta">${p.categoria}</span>
            <h3>${p.nombre}</h3>
            <p><strong>Categoría:</strong> ${p.categoria}</p>
            <p class="precio">S/. ${p.precio.toFixed(2)}</p>
            <div class="acciones-links">
                <a class="link" href="${p.video}" target="_blank">Video demostrativo</a>
                <a class="link" href="${p.ficha}" download>Descargar ficha técnica</a>
            </div>
            <div class="compra-producto">
                <button class="btn-carrito" onclick="agregarCarritoPorId(${p.id})">Agregar al carrito</button>
                <div class="cantidad-control">
                    <button type="button" onclick="cambiarCantidad(${p.id}, -1)">-</button>
                    <input id="cantidad-${p.id}" type="number" min="1" value="1">
                    <button type="button" onclick="cambiarCantidad(${p.id}, 1)">+</button>
                </div>
            </div>
        </article>
    `).join("");
}

function iniciarCatalogo() {
    if (!document.getElementById("productosGrid")) return;

    ["filtroNombre", "filtroCategoria", "precioMin", "precioMax", "ordenPrecio"].forEach(id => {
        document.getElementById(id).addEventListener("input", () => { pagina = 1; pintarProductos(); });
        document.getElementById(id).addEventListener("change", () => { pagina = 1; pintarProductos(); });
    });

    document.getElementById("limpiarFiltros").addEventListener("click", () => {
        document.getElementById("filtroNombre").value = "";
        document.getElementById("filtroCategoria").value = "";
        document.getElementById("precioMin").value = "";
        document.getElementById("precioMax").value = "";
        document.getElementById("ordenPrecio").value = "";
        pagina = 1;
        pintarProductos();
    });

    document.getElementById("btnAnterior").addEventListener("click", () => { if (pagina > 1) { pagina--; pintarProductos(); } });
    document.getElementById("btnSiguiente").addEventListener("click", () => { pagina++; pintarProductos(); });

    pintarProductos();
}

document.addEventListener("DOMContentLoaded", iniciarCatalogo);

// Exporta el catalogo completo (no solamente los productos de la pagina visible).
document.addEventListener("DOMContentLoaded", () => {
    const boton = document.getElementById("descargarReporteExcel");
    if (!boton) return;
    boton.addEventListener("click", async () => {
        boton.disabled = true;
        const anterior = boton.textContent;
        boton.textContent = "Generando Excel...";
        try {
            const respuesta = await fetch("/api/reportes/productos", {
                method: "POST",
                headers: {"Content-Type": "application/json"},
                body: JSON.stringify(productosFerreteria)
            });
            if (!respuesta.ok) throw new Error(await respuesta.text());
            const url = URL.createObjectURL(await respuesta.blob());
            const enlace = document.createElement("a");
            enlace.href = url;
            enlace.download = "productos_ferreteria.xlsx";
            document.body.appendChild(enlace);
            enlace.click();
            enlace.remove();
            setTimeout(() => URL.revokeObjectURL(url), 1000);
        } catch (error) {
            console.error("No se pudo generar el Excel:", error);
            alert("No se pudo generar el Excel. Comprueba que el servidor Java este iniciado en localhost:8080.");
        } finally {
            boton.disabled = false;
            boton.textContent = anterior;
        }
    });
});
